using System.Linq.Expressions;
using System.Reflection;

namespace Doka.EntityFrameworkCore.NestedSet.Samples.UserGroups;

/// <summary>Inlines the sample's exact ASCII text policy as ordinary translatable string expressions.</summary>
internal static class SupervisorExactText
{
    private static readonly ConstantExpression s_suffix = Expression.Constant("|");
    private static readonly ConstantExpression s_null = Expression.Constant(null, typeof(string));

    private static readonly MethodInfo s_concat = typeof(string).GetMethod(
        nameof(string.Concat),
        [typeof(string), typeof(string)])!;

    private static readonly MethodInfo s_equal = typeof(string).GetMethod(
        "op_Equality",
        [typeof(string), typeof(string)])!;

    private static readonly MethodInfo s_notEqual = typeof(string).GetMethod(
        "op_Inequality",
        [typeof(string), typeof(string)])!;

    /// <summary>Compares catalog identifiers without trimming or ignoring case.</summary>
    internal static bool FieldEquals(
        string? stored,
        string? requested
    ) => string.Equals(stored, requested, StringComparison.Ordinal);

    /// <summary>Matches two present, nonempty values without treating whitespace as missing data.</summary>
    internal static bool ValueEquals(
        string? left,
        string? right
    ) => !string.IsNullOrEmpty(left)
        && !string.IsNullOrEmpty(right)
        && string.Equals(left, right, StringComparison.Ordinal);

    /// <summary>Moves any trailing spaces inside the comparison without changing the original value.</summary>
    internal static string Suffix(
        string? value
    ) => value + "|";

    /// <summary>Expands only these three text operations before the expression is passed to EF.</summary>
    /// <param name="expression">The cached template or deferred query expression to translate.</param>
    /// <returns>An expression containing ordinary equality, concatenation, and explicit null/empty checks.</returns>
    internal static Expression Inline(
        Expression expression
    ) => new TextInliner().Visit(expression);

    /// <summary>Retains indexed field equality alongside the residual that makes trailing spaces significant.</summary>
    private static BinaryExpression FieldComparison(
        Expression stored,
        Expression requested
    ) => Expression.AndAlso(
        Expression.Equal(stored, requested, false, s_equal),
        Expression.Equal(Suffixed(stored), Suffixed(requested), false, s_equal));

    /// <summary>Requires actual values before comparing the complete, untrimmed strings.</summary>
    private static BinaryExpression ValueComparison(
        Expression left,
        Expression right
    ) => Expression.AndAlso(
        Present(left),
        Expression.AndAlso(Present(right), Expression.Equal(Suffixed(left), Suffixed(right), false, s_equal)));

    /// <summary>Distinguishes null/empty from a valid single-space value on PAD SPACE collations.</summary>
    private static BinaryExpression Present(
        Expression value
    ) => Expression.AndAlso(
        Expression.NotEqual(value, s_null, false, s_notEqual),
        Expression.NotEqual(Suffixed(value), s_suffix, false, s_notEqual));

    /// <summary>Uses the same framework concat operation generated by the original C# string expression.</summary>
    private static BinaryExpression Suffixed(
        Expression value
    ) => Expression.Add(value, s_suffix, s_concat);

    /// <summary>Expands known local text calls without introducing custom SQL functions or invocation nodes.</summary>
    private sealed class TextInliner : ExpressionVisitor
    {
        /// <inheritdoc />
        protected override Expression VisitMethodCall(
            MethodCallExpression node
        )
        {
            if (node.Method.DeclaringType != typeof(SupervisorExactText))
            {
                return base.VisitMethodCall(node);
            }

            // WHY: MySQL PAD SPACE and SQL Server ignore trailing spaces in ordinary string equality.
            // These residual expressions preserve the fixed comparison policy while leaving indexed equality visible.
            return node.Method.Name switch
            {
                nameof(FieldEquals) => FieldComparison(Visit(node.Arguments[0]), Visit(node.Arguments[1])),
                nameof(ValueEquals) => ValueComparison(Visit(node.Arguments[0]), Visit(node.Arguments[1])),
                nameof(Suffix) => Suffixed(Visit(node.Arguments[0])),
                _ => base.VisitMethodCall(node),
            };
        }
    }
}
