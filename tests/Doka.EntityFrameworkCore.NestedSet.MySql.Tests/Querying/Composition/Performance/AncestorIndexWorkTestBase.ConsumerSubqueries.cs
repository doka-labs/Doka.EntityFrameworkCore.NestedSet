using System.Globalization;
using System.Text;

namespace Doka.EntityFrameworkCore.NestedSet.Tests.MySql;

public abstract partial class AncestorIndexWorkTestBase
{
    /// <summary>Qualifies consumer EXISTS, IN and NOT EXISTS without changing inclusive occurrence bags.</summary>
    /// <param name="operation">The ordinary consumer semijoin or antijoin shape.</param>
    /// <param name="matches">Whether consumer facts match root and source owners or no owners.</param>
    [Theory]
    [InlineData("Any", false)]
    [InlineData("Any", true)]
    [InlineData("Contains", false)]
    [InlineData("Contains", true)]
    [InlineData("NotAny", false)]
    [InlineData("NotAny", true)]
    [Trait("Category", "Capacity")]
    public async Task InclusiveAncestorsPreserveConsumerSubqueryWork(
        string operation,
        bool matches
    )
    {
        // Arrange
        const int decoyFacts = 100_000;
        var scope = s_consumerScope;
        var tree = s_consumerTree;
        var commands = new CompositionCommandProbe();
        var capture = new EnterpriseProbe(captureParameterBindings: true);

        // WHY: A case-owned database gives paired binaries identical data, independent of test discovery order.
        await using var database = new ModelCompatibilityDatabase();
        await using var context = await database.CreateContextAsync<AncestorIndexQueryContext>(
            Engine,
            static options => new AncestorIndexQueryContext(options),
            commands,
            capture);

        await SeedAsync(context, scope, tree, forest: false);
        int[] selected = [20, 30];
        await SeedConsumerFactsAsync(context, scope, selected);
        await SeedUnrelatedConsumerFactsAsync(context, scope, decoyFacts);
        await context.Database.OpenConnectionAsync(CancellationToken.None);
        var label = matches ? "owner" : "missing";

        var expected = OrderConsumerPairs(
            ExpectedConsumerPairs(selected, chain: false, inclusive: true)
                .Where(pair => operation == "NotAny"
                    ? !matches || pair.Owner is not (1 or 20)
                    : matches && pair.Owner is 1 or 20));

        var profile = $"inclusive-consumer-{operation}-matches-{matches}";
        const string createIndex = "CREATE INDEX `IX_ConsumerFacts_Scope_Label_Node` "
            + "ON `AncestorIndexQueryItems` (`Scope`,`Label`,`NodeId`)";

        const string dropIndex = "DROP INDEX `IX_ConsumerFacts_Scope_Label_Node` ON `AncestorIndexQueryItems`";

        // WHY: A consumer owns the access path for its application predicate. The ancestor index
        // cannot index an unrelated fact label. This covering index is deliberately absent from
        // the shared model and removed after this case so other profiles retain their own schema.
        await context.Database.ExecuteSqlRawAsync(createIndex, CancellationToken.None);

        try
        {
            const string analyze = "ANALYZE TABLE `AncestorIndexQueryItems`";
            await context.Database.ExecuteSqlRawAsync(analyze, CancellationToken.None);
            await QueryPlanTestSupport.WriteEvidenceAsync(
                Engine + "-ancestor-consumer-owned-index-" + profile,
                ["Application-owned fact predicate index; not generated by HasAncestorIndex.", createIndex, dropIndex]);

            // Act
            var observation = await ObserveConsumerFactsAsync(
                context,
                commands,
                capture,
                Build,
                expected,
                profile,
                factRows: decoyFacts + 12);

            // Assert
            AssertConsumerFacts(observation, selected.Length);
        }
        finally
        {
            await context.Database.ExecuteSqlRawAsync(dropIndex, CancellationToken.None);
        }

        return;

        IQueryable<ConsumerFactPair> Build(
            AncestorIndexQueryContext source
        )
        {
            var owners = source
                .Set<CompositionNavigationItem>()
                .AsNoTracking()
                .Where(fact => fact.Scope == scope && fact.Label == label);

            var hierarchy = source
                .NestedSet<CompositionNavigationNode>()
                .ForScope(scope)
                .InTree(tree);

            var pairs = hierarchy.SelectAncestorsOrSelf(
                node => Enumerable.Contains(selected, node.Id),
                (innerSource, owner, distance) => new ConsumerHierarchyPair
                {
                    Source = innerSource.Id,
                    Owner = owner.Id,
                    Distance = distance
                });

            // WHY: These are three ordinary consumer shapes applied after eligible hierarchy composition.
            // Duplicate owner facts must act as membership tests, never multiply the occurrence bag.
            var filtered = operation switch
            {
                "Any" => pairs.Where(pair => owners.Any(owner => owner.NodeId == pair.Owner)),
                "Contains" => pairs.Where(pair => owners
                    .Select(owner => owner.NodeId)
                    .Contains(pair.Owner)),
                "NotAny" => pairs.Where(pair => !owners.Any(owner => owner.NodeId == pair.Owner)),
                _ => throw new ArgumentOutOfRangeException(nameof(operation)),
            };

            return WithConsumerOccurrences(source, scope, filtered);
        }
    }

    /// <summary>Exercises selective membership against substantial unrelated facts without tracking payload.</summary>
    private static async Task SeedUnrelatedConsumerFactsAsync(
        AncestorIndexQueryContext context,
        Guid scope,
        int facts
    )
    {
        var property =
            context.Model.FindEntityType(typeof(CompositionNavigationItem))!.FindProperty(
                nameof(CompositionNavigationItem.Scope))!;

        await using var parameterCommand = context
            .Database
            .GetDbConnection()
            .CreateCommand();

        for (var start = 0; start < facts; start += 1_000)
        {
            var sql = new StringBuilder(
                "INSERT INTO `AncestorIndexQueryItems` " + "(`Scope`,`Id`,`NodeId`,`Label`) VALUES ");

            for (var row = start; row < Math.Min(start + 1_000, facts); row++)
            {
                if (row != start)
                {
                    sql.Append(',');
                }

                // WHY: Fixed fixture identities keep these rows outside the selected sources and owners.
                // Bounded raw batches exercise native membership work without a population-sized EF tracker.
                sql.Append(CultureInfo.InvariantCulture, $"(@scope,{1_000_000 + row},99,'decoy')");
            }

            var scopeParameter = property
                .GetRelationalTypeMapping()
                .CreateParameter(parameterCommand, "scope", scope, nullable: false);

            await context.Database.ExecuteSqlRawAsync(sql.ToString(), [scopeParameter], CancellationToken.None);
        }

        const string analyze = "ANALYZE TABLE `AncestorIndexQueryItems`";
        await context.Database.ExecuteSqlRawAsync(analyze, CancellationToken.None);
    }
}
